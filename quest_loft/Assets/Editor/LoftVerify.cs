    static JObject Intent(string action, params string[] kv)
    {
        var o = new JObject { ["action"] = action };
        for (int i = 0; i + 1 < kv.Length; i += 2) o[kv[i]] = kv[i + 1];
        return o;
    }

    static JObject Resp(string action, bool needsConfirm, bool risky, JObject extra = null)
    {
        var intent = new JObject { ["action"] = action };
        if (extra != null) foreach (var kv in extra) intent[kv.Key] = kv.Value;
        return new JObject { ["transcript"] = "do the thing", ["summary"] = $"Summary of {action}", ["needsConfirm"] = needsConfirm, ["risky"] = risky, ["intent"] = intent };
    }

    // Tiny in-process backend: records every request, answers the voice contract.
    class FakeServer : System.IDisposable
    {
        public class Req
        {
            public string Method, Path, ContentType; public int BodyLength; public bool StartsWithRiff; public JObject Json; public bool Used;
        }
        readonly System.Net.HttpListener listener = new System.Net.HttpListener();
        readonly List<Req> reqs = new List<Req>();
        public string Url;
        public int nextStatus;
        public JObject voiceReply;
        public int Count { get { lock (reqs) return reqs.Count(r => !r.Used); } }

        public FakeServer()
        {
            var tcp = new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback, 0);
            tcp.Start(); int port = ((System.Net.IPEndPoint)tcp.LocalEndpoint).Port; tcp.Stop();
            Url = $"http://127.0.0.1:{port}";
            listener.Prefixes.Add(Url + "/");
            listener.Start();
            var t = new System.Threading.Thread(Loop) { IsBackground = true };
            t.Start();
        }

        void Loop()
        {
            while (listener.IsListening)
            {
                System.Net.HttpListenerContext c;
                try { c = listener.GetContext(); } catch { return; }
                try
                {
                    var body = new System.IO.MemoryStream();
                    c.Request.InputStream.CopyTo(body);
                    var bytes = body.ToArray();
                    var r = new Req { Method = c.Request.HttpMethod, Path = c.Request.Url.PathAndQuery, ContentType = c.Request.ContentType, BodyLength = bytes.Length,
                                      StartsWithRiff = bytes.Length > 4 && System.Text.Encoding.ASCII.GetString(bytes, 0, 4) == "RIFF" };
                    if (!r.Path.StartsWith("/voice?") && bytes.Length > 0) { try { r.Json = JObject.Parse(System.Text.Encoding.UTF8.GetString(bytes)); } catch { } }
                    lock (reqs) reqs.Add(r);
                    int status = nextStatus != 0 ? nextStatus : 200; nextStatus = 0;
                    string json = status != 200 ? "{\"error\":\"nope\"}" : (r.Path.StartsWith("/voice") && voiceReply != null ? voiceReply.ToString() : "{}");
                    var o = System.Text.Encoding.UTF8.GetBytes(json);
                    c.Response.StatusCode = status; c.Response.ContentType = "application/json"; c.Response.OutputStream.Write(o, 0, o.Length); c.Response.Close();
                }
                catch { }
            }
        }

        public Req Wait(string method, string pathStart, int ms = 3000)
        {
            var end = System.DateTime.UtcNow.AddMilliseconds(ms);
            while (System.DateTime.UtcNow < end)
            {
                lock (reqs)
                {
                    var r = reqs.FirstOrDefault(x => !x.Used && x.Method == method && x.Path.StartsWith(pathStart));
                    if (r != null) { r.Used = true; return r; }
                }
                System.Threading.Thread.Sleep(20);
            }
            return null;
        }

        public void Clear() { lock (reqs) reqs.Clear(); }
        public void Dispose() { try { listener.Stop(); listener.Close(); } catch { } }
    }

