#if UNITY_EDITOR
// Headless verifier for the Unity side (no backend, no headset needed):
//   Unity -batchmode -nographics -projectPath quest_loft \
//     -executeMethod LoftVerify.RunAll -quit -logFile Tools/verify.log
// Feeds REAL server event JSON (same shape as backend/src/orchestrator.js)
// into LoftDesk and checks the room reacts: animals spawn/animate/leave,
// boards update, themes load, panel/voice/teleport route, offline is safe.
// Backend logic itself is tested in backend/ (npm test).
using System.Linq;
using Newtonsoft.Json.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using VirtualLoft.XR;

public static class LoftVerify
{
    static int pass, fail;
    static void Check(bool ok, string step)
    {
        if (ok) { pass++; Debug.Log($"[VERIFY] PASS: {step}"); }
        else { fail++; Debug.LogError($"[VERIFY] FAIL: {step}"); }
    }

    static JObject Agent(string id, string role, string skin, string state = "idle") =>
        new JObject { ["id"] = id, ["name"] = id, ["role"] = new JObject { ["title"] = role, ["tools"] = new JArray("read_file") },
                      ["skin"] = skin, ["state"] = state, ["model"] = "qwen/qwen3-coder",
                      ["usage"] = new JObject { ["inputTokens"] = 1000, ["outputTokens"] = 200, ["costUsd"] = 0.0012 } };
    static JObject Task(string id, string agentId, string title, string status, string last = "", string result = "") =>
        new JObject { ["id"] = id, ["agentId"] = agentId, ["title"] = title, ["status"] = status, ["last"] = last, ["result"] = result };
    static string BoardText(string id) =>
        GameObject.Find($"Board_{id}")?.transform.Find("Content")?.GetComponent<TextMesh>()?.text ?? "";

    public static void RunAll()
    {
        pass = fail = 0;
        EditorSceneManager.OpenScene("Assets/Scenes/Loft.unity", OpenSceneMode.Single);
        LoftBootstrap.Build(); // the scene is generated from code: verify what the code builds
        var loft = GameObject.Find("Loft");
        var agents = Object.FindFirstObjectByType<AgentManager>();
        var desk = Object.FindFirstObjectByType<LoftDesk>();
        var world = Object.FindFirstObjectByType<LoftWorld>();
        var client = Object.FindFirstObjectByType<LoftClient>();
        var voice = Object.FindFirstObjectByType<VoiceCommands>();
        var panel = Object.FindFirstObjectByType<LoftQuestPanel>();
        var boards = Object.FindFirstObjectByType<BoardManager>();
        Check(loft && agents && desk && world && client && voice && panel && boards, "all Loft components present");
        if (fail > 0) { Finish(); return; }

        // Edit mode skips Awake: wire like runtime does.
        agents.Clear();
        world.Build();
        desk.agents = agents; desk.world = world; desk.client = client; desk.voice = voice;
        voice.OnCommand += (id, words) => lastVoice = (id, words);
        panel.EnsureBuilt();

        // 1. Themes: every JSON loads and applies; scenes really differ.
        var ids = LoftWorld.ThemeIds();
        Check(new[] { "beach", "loft", "meadow", "night", "party" }.All(ids.Contains), $"5 themes shipped ({string.Join(",", ids)})");
        Check(ids.All(world.ApplyTheme), "every theme applies");
        world.ApplyTheme("beach"); var beachBg = world.cam.backgroundColor;
        world.ApplyTheme("party"); var partyBg = world.cam.backgroundColor;
        int props = GameObject.Find("ThemeProps").transform.childCount;
        Check(beachBg != partyBg && props == world.Current.props.Count, $"party swaps sky + spawns its {props} props");
        Check(!world.ApplyTheme("does-not-exist") && world.Current.id == "party", "unknown theme ignored, scene kept");

        // 1b. Sound: every clip the game asks for loads (generated by audiogen/gen.py).
        var wantedClips = ids.Select(id => LoftWorld.LoadTheme(id)?.audio).Where(clipName => !string.IsNullOrEmpty(clipName))
            .Concat(new[] { "party", "sfx_click", "sfx_spawn", "sfx_remove", "sfx_done", "sfx_failed", "sfx_approve", "sfx_reject",
                            "sfx_teleport", "sfx_party_horn", "sfx_confetti_pop" })
            .Concat(new[] { "fox", "owl", "cat", "bear", "rabbit", "penguin", "frog", "panda" }.Select(an => "voice_" + an)).ToList();
        var missingClips = wantedClips.Where(clipName => LoftAudio.Clip(clipName) == null).ToList();
        Check(missingClips.Count == 0, $"all {wantedClips.Count} sounds load from Resources/Audio (missing: {string.Join(",", missingClips)})");
        var partyClip = LoftAudio.Clip("party");
        Check(partyClip != null && Mathf.Abs(partyClip.length - 16f) < 0.05f, "party track is the 16 s / 120 BPM loop");

        // 2. Default team of 3 arrives in a snapshot; unknown skin -> placeholder.
        desk.HandleEvent(new JObject
        {
            ["type"] = "snapshot", ["maxAgents"] = 20,
            ["agents"] = new JArray(Agent("scout-1", "scout", "owl"), Agent("builder-2", "builder", "fox"), Agent("keeper-3", "keeper", "dragon")),
            ["tasks"] = new JArray(),
        });
        Check(agents.agents.Count == 3, $"snapshot -> 3 animals (got {agents.agents.Count})");
        var keeper = agents.Find("keeper-3");
        Check(keeper != null && keeper.transform.Find("Model") != null && keeper.GetComponent<Collider>() != null,
            "unknown skin 'dragon' -> placeholder model + pick collider");

        // 3. Real task lifecycle drives state + boards (no timers anywhere).
        desk.HandleEvent(new JObject { ["type"] = "task", ["task"] = Task("t1", "builder-2", "add login page", "running", "Edit src/login.ts") });
        desk.HandleEvent(new JObject { ["type"] = "agent", ["agent"] = Agent("builder-2", "builder", "fox", "working") });
        var builder = agents.Find("builder-2");
        Check(builder.CurrentState == AgentState.Working, "agent event 'working' -> Working");
        Check(builder.GetComponent<AgentSkin>().line == "Edit src/login.ts", "live progress line on the animal");
        Check(BoardText("kanban").Contains("Doing(1)"), "kanban board shows the running task");
        desk.HandleEvent(new JObject { ["type"] = "task", ["task"] = Task("t1", "builder-2", "add login page", "review", "", "PASS 3/3 — login.ts added") });
        desk.HandleEvent(new JObject { ["type"] = "agent", ["agent"] = Agent("builder-2", "builder", "fox", "done") });
        Check(builder.CurrentState == AgentState.Done, "review -> animal Done");
        Check(BoardText("notes").Contains("login.ts added"), "REVIEW board shows the result for the CEO");
        Check(desk.ReviewTask()?.id == "t1", "approve/reject target = task in review");

        // 4. Spawn up to 20, never more; layout stays distinct.
        for (int i = 4; i <= 21; i++) desk.HandleEvent(new JObject { ["type"] = "agent", ["agent"] = Agent($"builder-{i}", "builder", "cat") });
        Check(agents.agents.Count == 20, $"room caps at 20 animals (got {agents.agents.Count})");
        var homes = agents.agents.Select(a => a.GetComponent<AgentSkin>().home).ToList();
        Check(homes.Distinct().Count() == 20, "20 distinct seats");
        desk.HandleEvent(new JObject { ["type"] = "agent.removed", ["id"] = "builder-4" });
        Check(agents.agents.Count == 19 && GameObject.Find("Agent_builder-4") == null, "agent.removed -> animal leaves");
        desk.HandleEvent(new JObject { ["type"] = "snapshot", ["agents"] = new JArray(Agent("scout-1", "scout", "owl")), ["tasks"] = new JArray() });
        Check(agents.agents.Count == 1, "reconnect snapshot drops agents the server no longer has");

        // 5. Panel: 9 pointable buttons; pointing routes to actions.
        var root = GameObject.Find("QuestPanel");
        Check(root != null && root.GetComponentsInChildren<Collider>().Length == 10, "VR console: 10 buttons with colliders incl. ★ PARTY (new-agent page hidden)");
        // New-agent page: form state is shared with the desktop panel.
        desk.HandleEvent(new JObject { ["type"] = "roles", ["roles"] = new JArray(
            new JObject { ["id"] = "scout", ["title"] = "Researcher", ["tools"] = new JArray("read_file") },
            new JObject { ["id"] = "builder", ["title"] = "Coder", ["tools"] = new JArray("write_file", "run_command") }) });
        panel.Click(root.transform.Find("Main/Btn_spawn/Face").gameObject);
        Check(root.transform.Find("Spawn").gameObject.activeSelf && !root.transform.Find("Main").gameObject.activeSelf, "+ AGENT opens the new-agent page");
        desk.formRoleId = "scout";
        panel.Click(root.transform.Find("Spawn/Btn_role/Face").gameObject);
        panel.Click(root.transform.Find("Spawn/Btn_animal/Face").gameObject);
        desk.formModel = "qwen/qwen3-coder";
        Check(desk.formRoleId == "builder" && desk.formSkin != "random" && desk.FormSummary().Contains("⚠") && desk.FormSummary().Contains("qwen/qwen3-coder"),
            $"form cycles role/animal, flags write tools, shows the typed model ({desk.FormSummary()})");
        desk.formDraft = new JObject { ["title"] = "A11y Checker", ["instructions"] = "check", ["tools"] = new JArray("read_file", "run_command") };
        desk.ToggleDraftTool("run_command");
        Check(!desk.FormTools().Contains("run_command") && desk.FormSummary().StartsWith("NEW A11y Checker"), "AI-written role: CEO can remove a risky tool before CREATE");
        desk.formDraft = null;
        panel.Click(root.transform.Find("Spawn/Btn_back/Face").gameObject);
        Check(root.transform.Find("Main").gameObject.activeSelf, "BACK returns to the main console");
        var before = world.Current.id;
        panel.Click(root.transform.Find("Main/Btn_theme/Face").gameObject);
        Check(world.Current.id != before, "pointing at SCENE ▶ switches theme");
        panel.Click(agents.Find("scout-1").gameObject);
        Check(desk.selectedAgentId == "scout-1", "pointing at an animal selects it");
        panel.TeleportTo(1);
        var cam = world.cam.transform.position;
        Check(Vector3.Distance(cam, new Vector3(0f, Comfort.SEATED_EYE_HEIGHT, 5.2f)) < 0.05f, $"teleport moves the rig, eye height kept ({cam})");

        // 5b. Party mode: everyone gathers on the dance floor, then goes back to work.
        client.serverUrl = "http://127.0.0.1:49999"; // never switch a real dev backend's party on
        LoftClient.timeoutSeconds = 4;
        var party = Object.FindFirstObjectByType<LoftParty>();
        Check(party != null, "LoftParty in scene");
        if (party != null)
        {
            desk.party = party;
            party.agents = agents;
            party.world = world;
            for (int i = 2; i <= 9; i++) desk.HandleEvent(new JObject { ["type"] = "agent", ["agent"] = Agent($"dancer-{i}", "builder", "random") });
            agents.Find("dancer-3").SetState(AgentState.Working);
            panel.Click(root.transform.Find("Main/Btn_party/Face").gameObject);
            var partyRoot = GameObject.Find("PartyMode"); // findable only while active
            Check(party.On && agents.Partying && partyRoot != null && GameObject.Find("DiscoBall") != null,
                "★ PARTY button: disco ball, dance floor, everyone partying");
            var spots = AgentManager.PartySpots(agents.agents.Count);
            bool spread = true;
            for (int i = 0; i < spots.Count; i++)
                for (int j = i + 1; j < spots.Count; j++)
                    if (Vector3.Distance(spots[i], spots[j]) < 0.7f) spread = false;
            Check(spread && spots.All(sp => sp.z < LoftParty.Center.z && Mathf.Abs(sp.x) < 4.5f),
                $"{spots.Count} dancers get their own spot on the floor (>= 0.7 m apart, facing the CEO)");
            Check(agents.agents.All(a => a.GetComponent<AgentSkin>().partying), "every agent switched to the Party dance");
            desk.HandleEvent(new JObject { ["type"] = "agent", ["agent"] = Agent("latecomer-99", "builder", "fox") });
            Check(agents.Find("latecomer-99").GetComponent<AgentSkin>().partying, "an agent spawned mid-party joins the dance");
            desk.HandleEvent(new JObject { ["type"] = "party", ["on"] = false });
            Check(!party.On && !agents.Partying && agents.agents.All(a => !a.GetComponent<AgentSkin>().partying)
                  && agents.Find("dancer-3").CurrentState == AgentState.Working,
                "server 'party off': back to seats, real work state kept (Working)");
            Check(partyRoot != null && !partyRoot.activeSelf, "party props hidden again");
            var big = AgentManager.PartySpots(20);
            Check(big.All(sp => sp.z > 0.5f) && big.Distinct().Count() == 20, "20 dancers: nobody dances inside the wall");
            // back to a 1-agent team for the next steps
            desk.HandleEvent(new JObject { ["type"] = "snapshot", ["agents"] = new JArray(Agent("scout-1", "scout", "owl")), ["tasks"] = new JArray() });
        }

        // 6. Voice: longest phrase wins, payload kept, no false prefix hits.
        voice.testMode = true;
        voice.HandleTranscription("jalankan tambah halaman login");
        Check(lastVoice.id == VoiceCommandId.Run && lastVoice.words == "tambah halaman login", $"voice ID run -> goal payload ('{lastVoice.words}')");
        voice.HandleTranscription("Run Add Dark Mode");
        Check(lastVoice.words == "Add Dark Mode", "voice payload keeps casing");
        Check(!voice.HandleTranscription("running late"), "'running late' is not 'run'");
        voice.HandleTranscription("ayo pesta");
        Check(lastVoice.id == VoiceCommandId.Party, "voice 'ayo pesta' / 'party time' -> Party");

        // 7. Offline: commands degrade to null, nothing throws, room intact.
        client.serverUrl = "http://127.0.0.1:49999";
        LoftClient.timeoutSeconds = 4;
        bool offlineOk;
        try
        {
            offlineOk = client.Spawn("qwen/qwen3-coder", "builder").GetAwaiter().GetResult() == null
                && client.Goal("x").GetAwaiter().GetResult() == null
                && !client.CheckHealthAsync().GetAwaiter().GetResult();
        }
        catch (System.Exception e) { Debug.LogError(e); offlineOk = false; }
        Check(offlineOk && agents.agents.Count == 1, "backend down -> commands return null, room unchanged");

        // 8. Board store never bricks on bad JSON.
        int n = boards.ListCards("kanban").Count;
        boards.Load("{not json");
        boards.Load("{\"boards\":null}");
        Check(boards.ListCards("kanban").Count == n, "corrupt board JSON ignored");

        // 9. Generated animals (animalgen/ -> Models/Animals/*.fbx -> Resources/Skins/*.prefab).
        LoftAnimalImport.RebuildAll();
        foreach (var fbx in System.IO.Directory.GetFiles(LoftAnimalImport.Dir, "*.fbx"))
        {
            var id = System.IO.Path.GetFileNameWithoutExtension(fbx);
            var prefab = Resources.Load<GameObject>($"Skins/{id}");
            Check(prefab != null, $"animal '{id}': prefab in Resources/Skins");
            if (prefab == null) continue;
            var animator = prefab.GetComponent<Animator>(); // explicit null test: Unity's missing-component null
            var ctrl = animator != null ? animator.runtimeAnimatorController as UnityEditor.Animations.AnimatorController : null;
            bool stateParam = ctrl != null && ctrl.parameters.Any(par => par.name == "State" && par.type == AnimatorControllerParameterType.Int);
            var states = ctrl != null ? ctrl.layers[0].stateMachine.states.Select(cs => cs.state).ToList() : new System.Collections.Generic.List<UnityEditor.Animations.AnimatorState>();
            Check(stateParam && LoftAnimalImport.States.All(want => states.Any(st => st.name == want && st.motion != null)),
                $"animal '{id}': Animator int State + Idle/Working/Done/Failed clips");
            var go = Object.Instantiate(prefab);
            var head = go.GetComponentsInChildren<Transform>().FirstOrDefault(t => t.name == "head");
            var tail = go.GetComponentsInChildren<Transform>().FirstOrDefault(t => t.name == "tail.3");
            var earL = go.GetComponentsInChildren<Transform>().FirstOrDefault(t => t.name == "ear.L");
            Check(head && tail && earL && tail.position.z < head.position.z && earL.position.x < 0f && head.position.y > 0.4f,
                $"animal '{id}': upright, faces +Z, not mirrored (head {head?.position}, tail {tail?.position})");
            var r = go.GetComponentInChildren<SkinnedMeshRenderer>();
            float h = r != null ? r.bounds.size.y : 0f;
            Check(r != null && h > 0.8f && h < 1.4f && r.sharedMaterial != null && r.sharedMaterial.shader.name == "Loft/VertexColorLit",
                $"animal '{id}': {h:F2} m tall, vertex-color material");
            Object.DestroyImmediate(go);
        }

        Finish();
    }

    static (VoiceCommandId id, string words) lastVoice;

    static void Finish()
    {
        PlayerPrefs.DeleteKey("loft.theme"); // verify switched themes; don't leak that into the next Play
        Debug.Log($"[VERIFY] SUMMARY: {pass} pass, {fail} fail — {(fail == 0 ? "GREEN" : "RED")}");
        if (Application.isBatchMode) EditorApplication.Exit(fail == 0 ? 0 : 1);
    }
}
#endif
